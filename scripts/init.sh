#!/bin/bash

# 전달받은 첫 번째 인자 사용 (없으면 기본값 사용)
NAME=${1:-"User"}
DATE=$(date +"%Y-%m-%d %H:%M:%S")

echo "========================================"
echo "시스템 알림: 테스트 스크립트 실행됨"
echo "실행 시간: $DATE"
echo "환영합니다, $NAME님!"
echo "========================================"

# 특정 로직이 성공했음을 알리는 의미로 0을 반환
exit 0
